export type WarmthTier = 'low' | 'mid' | 'high'

/**
 * 分界点。⚠️ **仍未拍板**，沿用第一轮比稿自取的口径（0.55 / 0.8）。
 * 换分界点只改「哪扇窗落在哪一档」，不改上面任何一条红线。
 */
export function warmthTier(w: number): WarmthTier {
  if (w >= 0.8) return 'high'
  if (w >= 0.55) return 'mid'
  return 'low'
}

/** 三档文案。🔴 一套，读的人是谁都成立。改之前先读本文件顶部两条红线。 */
export const WARMTH_PHRASE: Record<WarmthTier, string> = {
  low: '这扇窗为它留着',
  mid: '它常常被想起',
  high: '它一直被记着',
}

export function warmthPhrase(w: number): string {
  return WARMTH_PHRASE[warmthTier(w)]
}
